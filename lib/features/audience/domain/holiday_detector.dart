/// 节日检测器
///
/// 本地维护公历和农历节日表，跑步开始时检测是否命中
/// 农历日期使用内置映射表（2025-2035），超出范围时静默跳过农历检测
/// TODO: 映射表需定期更新，建议在 2034 年前补充 2036+ 年数据
class HolidayDetector {
  HolidayDetector._();

  /// 检测给定日期是否命中节日
  ///
  /// 返回节日名称，如果未命中则返回 null
  static String? detect(DateTime date) {
    // 优先匹配公历节日
    final key = '${date.month}-${date.day}';
    if (_solarHolidays.containsKey(key)) {
      return _solarHolidays[key]!;
    }

    // 农历节日：直接用公历日期匹配内置映射表
    final yearMap = _lunarMapping[date.year];
    if (yearMap != null) {
      final dateKey = '${date.month}-${date.day}';
      if (yearMap.containsKey(dateKey)) {
        return yearMap[dateKey];
      }
    }

    return null;
  }

  /// 判断是否为周末
  static bool isWeekend(DateTime date) {
    final weekday = date.weekday;
    return weekday == DateTime.saturday || weekday == DateTime.sunday;
  }

